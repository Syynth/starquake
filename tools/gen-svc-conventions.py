#!/usr/bin/env python3
"""Generates the kernel's system-call register convention from Eden's generated wrappers.

Reads, from the reference folder (`tools/refs-path.sh`, `docs/references.md`):

    eden/src/core/hle/kernel/svc.cpp        the `SvcWrap_<Name>64` wrappers and the
                                            `static_assert(sizeof(T) == n)` lines

and, from this repository, `crates/kernel/src/svc/reference/svc_ids.txt` (the call numbers).

Writes, under `crates/kernel/src/svc/`:

    reference/svc_wrappers64.txt    one line per call: which register carries each argument
                                    and each output
    reference/svc_type_sizes.txt    the size Eden asserts for each type the wrappers use
    convention/table.rs             the `CONVENTIONS` rows, for the calls retail titles may make

Usage, from the repository root:

    tools/gen-svc-conventions.py            # rewrite the three files
    tools/gen-svc-conventions.py --check    # exit 1 if any of them would change

The wrappers Eden writes by hand (light IPC, the secure monitor) and the Switch 2 call
`SetGpuMemoryAttribute` have no generated wrapper; their lines are in `HAND_TRANSCRIBED` below,
each with its source. `table.rs` is formatted with `rustfmt`, which must be on the path.
"""

import pathlib
import re
import subprocess
import sys

REPO = pathlib.Path(__file__).resolve().parent.parent
SVC = REPO / "crates" / "kernel" / "src" / "svc"
WRAPPERS = SVC / "reference" / "svc_wrappers64.txt"
SIZES = SVC / "reference" / "svc_type_sizes.txt"
IDS = SVC / "reference" / "svc_ids.txt"
TABLE = SVC / "convention" / "table.rs"

EDEN_SVC = "eden/src/core/hle/kernel/svc.cpp"
EDEN_COMMIT = "cf654052"

# Retail titles may call 0x01-0x36 and 0x80 (`is_retail` in `svc/convention.rs`, from
# eden-nx2/NX2_NOTES.md @ 50fa86bb); only those get a row in `table.rs`.
RETAIL_FIRST = 0x01
RETAIL_LAST = 0x36
RETAIL_EXTRA = 0x80

WRAPPERS_HEADER = f"""\
# 64-bit register convention of every system call, one line per call:
#   Name | input:type:register ... | output:type:register ...
# Extracted by script from the generated `SvcWrap_<Name>64` wrappers in
# {EDEN_SVC} @ {EDEN_COMMIT} (GPL-3.0-or-later): each
# `T name = Convert<T>(GetArg64(args, n))` is an input, each `SetArg64(args, n, ...)` an output;
# `name[k]` is element k of a struct scattered over several registers. Calls without a
# generated wrapper are transcribed by hand at the end, with their source.
# Checked against `CONVENTIONS` by the tests in `svc/convention.rs`.
"""

HAND_TRANSCRIBED = """\
# Hand-transcribed: `SvcWrap_LightIpc` in eden/src/core/hle/kernel/svc/svc_light_ipc.cpp @ cf654052.
# x0 is the session handle in and the result out; x1-x7 carry seven 32-bit words both ways.
SendSyncRequestLight | session_handle:Handle:x0 args[0]:uint32_t:x1 args[1]:uint32_t:x2 args[2]:uint32_t:x3 args[3]:uint32_t:x4 args[4]:uint32_t:x5 args[5]:uint32_t:x6 args[6]:uint32_t:x7 | ret:Result:x0 args[0]:uint32_t:x1 args[1]:uint32_t:x2 args[2]:uint32_t:x3 args[3]:uint32_t:x4 args[4]:uint32_t:x5 args[5]:uint32_t:x6 args[6]:uint32_t:x7
ReplyAndReceiveLight | session_handle:Handle:x0 args[0]:uint32_t:x1 args[1]:uint32_t:x2 args[2]:uint32_t:x3 args[3]:uint32_t:x4 args[4]:uint32_t:x5 args[5]:uint32_t:x6 args[6]:uint32_t:x7 | ret:Result:x0 args[0]:uint32_t:x1 args[1]:uint32_t:x2 args[2]:uint32_t:x3 args[3]:uint32_t:x4 args[4]:uint32_t:x5 args[5]:uint32_t:x6 args[6]:uint32_t:x7
# Hand-transcribed: the `SetGpuMemoryAttribute` case of `Call64` in
# eden-pr4588/src/core/hle/kernel/svc.cpp @ e5fb3b97 (`args[0..3]`, mask and attr cast to u32,
# result written to `args[0]`).
SetGpuMemoryAttribute | address:uint64_t:x0 size:uint64_t:x1 mask:uint32_t:x2 attr:uint32_t:x3 | ret:Result:x0
# Hand-transcribed: `SvcWrap_CallSecureMonitor64` in
# eden/src/core/hle/kernel/svc/svc_secure_monitor_call.cpp @ cf654052: x0-x7 copied into
# `lp64::SecureMonitorArguments::r` and back.
CallSecureMonitor | r[0]:uint64_t:x0 r[1]:uint64_t:x1 r[2]:uint64_t:x2 r[3]:uint64_t:x3 r[4]:uint64_t:x4 r[5]:uint64_t:x5 r[6]:uint64_t:x6 r[7]:uint64_t:x7 | r[0]:uint64_t:x0 r[1]:uint64_t:x1 r[2]:uint64_t:x2 r[3]:uint64_t:x3 r[4]:uint64_t:x4 r[5]:uint64_t:x5 r[6]:uint64_t:x6 r[7]:uint64_t:x7
"""

SIZES_HEADER = f"""\
# The size in bytes Eden asserts for each type its system-call wrappers pass in a register:
# the `static_assert(sizeof(T) == n)` lines of {EDEN_SVC} @ {EDEN_COMMIT}
# (GPL-3.0-or-later), for the types `svc_wrappers64.txt` names. Extracted by
# `tools/gen-svc-conventions.py`.
# Checked against `Kind::bytes` by the tests in `svc/convention.rs`.
"""

TABLE_HEADER = """\
//! The rows of [`CONVENTIONS`], generated by `tools/gen-svc-conventions.py` from
//! `../reference/svc_wrappers64.txt` and checked against it entry by entry by the tests in
//! `convention.rs`.
"""

# Eden's type -> the `Kind` that carries it, for the types with a kind of their own. Any other
# type is a `Kind::Word`, which is 4 bytes, so the script refuses one Eden does not assert to be
# 4 bytes.
KINDS = {
    "uint64_t": ("U64", 8),
    "int64_t": ("I64", 8),
    "uint32_t": ("U32", 4),
    "int32_t": ("I32", 4),
    "Handle": ("Handle", 4),
    "Result": ("Kind::Result", 4),
    "bool": ("Bool", 1),
}
WORD_BYTES = 4


def fail(message):
    sys.exit(f"gen-svc-conventions: {message}")


def refs_folder():
    out = subprocess.run(
        [str(REPO / "tools" / "refs-path.sh")], capture_output=True, text=True, check=True
    )
    return pathlib.Path(out.stdout.strip())


def asserted_sizes(source):
    """`{type: bytes}` from the `static_assert(sizeof(T) == n);` lines."""
    return {
        name: int(size)
        for name, size in re.findall(r"^static_assert\(sizeof\(([\w:]+)\) == (\d+)\);$", source, re.M)
    }


def generated_wrappers(source):
    """`[(name, inputs, outputs)]` for every `SvcWrap_<Name>64`, in file order.

    An input or output is `(name, type, register)`.
    """
    wrappers = []
    pattern = re.compile(
        r"^static void SvcWrap_(\w+?)64\(Core::System& system, std::span<uint64_t, 8> args\) \{\n(.*?)^\}",
        re.M | re.S,
    )
    for name, body in pattern.findall(source):
        locals_, inputs, outputs = {}, [], []
        for line in body.splitlines():
            line = line.strip()
            # `T name = Convert<T>(GetArg64(args, n));`
            if match := re.fullmatch(r"([\w:]+) (\w+) = Convert<([\w:]+)>\(GetArg64\(args, (\d+)\)\);", line):
                ty, arg, converted, reg = match.groups()
                if ty != converted:
                    fail(f"{name}: `{line}` converts to a different type than it declares")
                inputs.append((arg, ty, int(reg)))
            # `T name{};` declares an output.
            elif match := re.fullmatch(r"([\w:]+) (\w+)\{\};", line):
                locals_[match.group(2)] = match.group(1)
            # `auto name_scatter = Convert<std::array<uint64_t, N>>(name);`
            elif match := re.fullmatch(r"auto (\w+)_scatter = Convert<std::array<uint64_t, \d+>>\((\w+)\);", line):
                if match.group(1) != match.group(2):
                    fail(f"{name}: `{line}` scatters under another name")
            # `SetArg64(args, n, Convert<uint64_t>(name));`
            elif match := re.fullmatch(r"SetArg64\(args, (\d+), Convert<uint64_t>\((\w+)\)\);", line):
                reg, arg = match.groups()
                outputs.append((arg, locals_[arg], int(reg)))
            # `SetArg64(args, n, name_scatter[k]);`
            elif match := re.fullmatch(r"SetArg64\(args, (\d+), (\w+)_scatter\[(\d+)\]\);", line):
                reg, arg, element = match.groups()
                outputs.append((f"{arg}[{element}]", "uint64_t", int(reg)))
            # The call itself: `Result ret = Name64(system, ...);`, `T ret = ...;` or `Name64(...);`
            elif match := re.fullmatch(r"(?:([\w:]+) (\w+) = )?\w+64\(system.*\);", line):
                if match.group(1):
                    locals_[match.group(2)] = match.group(1)
            elif line:
                fail(f"{name}: unrecognised line `{line}`")
        wrappers.append((name, inputs, outputs))
    return wrappers


def render_args(args):
    return " ".join(f"{name}:{ty}:x{reg}" for name, ty, reg in args)


def render_line(name, inputs, outputs):
    return f"{name} | {render_args(inputs)} | {render_args(outputs)}"


def parse_line(line):
    name, inputs, outputs = (column.strip() for column in line.split("|"))

    def args(column):
        parsed = []
        for item in column.split():
            arg, ty, reg = item.split(":")
            parsed.append((arg, ty, int(reg.removeprefix("x"))))
        return parsed

    return name, args(inputs), args(outputs)


def call_numbers():
    numbers = {}
    for line in IDS.read_text().splitlines():
        if line.startswith("#") or not line.strip():
            continue
        name, number = line.split(" = ")
        numbers[name.strip()] = int(number, 16)
    return numbers


def is_retail(number):
    return RETAIL_FIRST <= number <= RETAIL_LAST or number == RETAIL_EXTRA


def kind_of(call, ty, sizes):
    if ty in KINDS:
        kind, size = KINDS[ty]
    else:
        kind, size = f'Word("{ty}")', WORD_BYTES
    if sizes.get(ty) != size:
        fail(f"{call}: Eden asserts sizeof({ty}) == {sizes.get(ty)}, but its kind is {size} bytes")
    return kind


def render_table(calls, sizes):
    rows, used = [], set()
    for name, inputs, outputs in calls:
        def args(items):
            rendered = []
            for arg, ty, reg in items:
                kind = kind_of(name, ty, sizes)
                used.add(kind.split("(")[0])
                rendered.append(f'arg("{arg}", {reg}, {kind})')
            return ", ".join(rendered)

        rows.append(
            f"(SvcId::{name}, Convention {{ inputs: &[{args(inputs)}], outputs: &[{args(outputs)}] }}),"
        )
    imports = sorted(kind for kind in used if not kind.startswith("Kind::"))
    return (
        TABLE_HEADER
        + "\n"
        + f"use super::Kind::{{self, {', '.join(imports)}}};\n"
        + "use super::{Arg, Convention};\n"
        + "use crate::svc::SvcId;\n\n"
        + "const fn arg(name: &'static str, reg: u8, kind: Kind) -> Arg {\n"
        + "    Arg { name, reg, kind }\n"
        + "}\n\n"
        + "/// The register convention of every [`is_retail`](super::is_retail) call, in number order.\n"
        + "pub static CONVENTIONS: &[(SvcId, Convention)] = &[\n"
        + "\n".join(rows)
        + "\n];\n"
    )


def rustfmt(text):
    out = subprocess.run(
        ["rustfmt", "--edition", "2024", "--emit", "stdout"],
        input=text,
        capture_output=True,
        text=True,
        cwd=REPO,
    )
    if out.returncode != 0:
        fail(f"rustfmt failed: {out.stderr}")
    return out.stdout


def main():
    check = sys.argv[1:] == ["--check"]
    if sys.argv[1:] and not check:
        fail("usage: gen-svc-conventions.py [--check]")
    source = (refs_folder() / EDEN_SVC).read_text()
    sizes = asserted_sizes(source)

    generated = generated_wrappers(source)
    lines = [render_line(*wrapper) for wrapper in generated]
    wrappers_text = WRAPPERS_HEADER + "\n".join(lines) + "\n" + HAND_TRANSCRIBED

    calls = [parse_line(line) for line in wrappers_text.splitlines() if not line.startswith("#")]
    used_types = sorted({ty for _, inputs, outputs in calls for _, ty, _ in inputs + outputs})
    for ty in used_types:
        if ty not in sizes:
            fail(f"Eden asserts no size for {ty}")
    sizes_text = SIZES_HEADER + "".join(f"{ty} = {sizes[ty]}\n" for ty in used_types)

    numbers = call_numbers()
    for name, _, _ in calls:
        if name not in numbers:
            fail(f"{name} has a wrapper but no number in {IDS.name}")
    retail = sorted(
        (call for call in calls if is_retail(numbers[call[0]])), key=lambda call: numbers[call[0]]
    )
    table_text = rustfmt(render_table(retail, sizes))

    stale = []
    for path, text in [(WRAPPERS, wrappers_text), (SIZES, sizes_text), (TABLE, table_text)]:
        if path.exists() and path.read_text() == text:
            continue
        stale.append(path.relative_to(REPO))
        if not check:
            path.write_text(text)
    if check and stale:
        fail("out of date: " + ", ".join(str(path) for path in stale))
    for path in stale:
        print(f"wrote {path}")


if __name__ == "__main__":
    main()
