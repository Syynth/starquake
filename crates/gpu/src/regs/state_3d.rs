//! The 3D class's plain-state methods ([`STATE_3D`]): the methods whose same-value writes the
//! front may drop (gpu-protocol spec, "Engine methods: the register file", step 3; owner's
//! decision 12). A method not listed is a trigger and is always sent, so a missing entry costs
//! speed, never correctness.
//!
//! Written by hand once from the generated `clc797` table, by this rule, and kept by hand: a
//! method is listed when
//!
//! - its name starts with `SET_`, or it is one of the plain registers
//!   `LOAD_CONSTANT_BUFFER_OFFSET`, `LOAD_MME_START_ADDRESS_RAM_POINTER` and the
//!   inline-to-memory geometry `LINE_LENGTH_IN`, `LINE_COUNT`, `OFFSET_OUT_UPPER`, `OFFSET_OUT`
//!   and `PITCH_OUT` (Eden-NX2 treats all seven as plain state: none is in its
//!   `IsMethodExecutable`, `eden-nx2/src/video_core/engines/maxwell_3d.cpp`);
//! - and it is not one of these `SET_` methods:
//!   - the ones Eden-NX2's `IsMethodExecutable` acts on: `SET_MME_SHADOW_RAM_CONTROL`
//!     (`shadow_ram_control`), `SET_VERTEX_ARRAY_START` (`vertex_buffer.first`),
//!     `SET_INDEX_BUFFER_F` (`index_buffer.first`), `SET_PRIMITIVE_TOPOLOGY`
//!     (`topology_override`), `SET_REPORT_SEMAPHORE_D` (`report_semaphore.query`),
//!     `SET_RENDER_ENABLE_C` (`render_enable.mode`) and `SET_FALCON04` (`falcon[4]`);
//!   - `SET_ROOT_TABLE_SELECTOR`, which PR #4588's `IsMethodExecutable` acts on
//!     (`eden-pr4588/src/video_core/engines/maxwell_3d.cpp`);
//!   - `SET_OBJECT` (method 0, a host method);
//!   - the rest of `SET_FALCON00` to `SET_FALCON31` (firmware calls, as Eden calls
//!     `falcon[4]`), `SET_RESERVED_SW_METHOD00` to `15` (software methods), `SET_SPARE00` to
//!     `03`, `SET_SPARE_NOOP01` to `15`, `SET_I2M_SPARE_NOOP00` to `03`,
//!     `SET_INSTRUMENTATION_METHOD_HEADER`, `SET_INSTRUMENTATION_METHOD_DATA` and
//!     `SET_MME_SWITCH_STATE`: **guesses** that any of these may act, left as triggers since
//!     dropping their writes gains nothing measured;
//! - and, for an array method, it has one index and Mesa gives its length (`METHOD_ARRAY_SIZES`
//!   in `mesa-nouveau/src/nouveau/headers/class_parser.py`, MIT; each length below is Mesa's).
//!   Left out for want of a length: `SET_POSITION_W_SCALED_OFFSET_SCALE_A` and `_B`,
//!   `SET_POSITION_W_SCALED_OFFSET_RESERVED_A` and `_B`, `SET_TIR_MODULATION_COEFFICIENT_TABLE`,
//!   `SET_DA_OUTPUT_ATTRIBUTE_SKIP_MASK_A` and `_B`, `SET_POST_VTG_SHADER_ATTRIBUTE_SKIP_MASK`,
//!   `SET_ITERATED_BLEND_CONSTANT_RED`, `_GREEN` and `_BLUE`, `SET_LINE_SMOOTH_EDGE_TABLE`,
//!   `SET_POLYGON_STIPPLE_PATTERN` and `SET_VARIABLE_PIXEL_RATE_SHADING_RESERVED_A`; for having
//!   two indices: `SET_STREAM_OUT_LAYOUT_SELECT`.
//!
//! Every listed method is one Eden-NX2 drops same-value writes to as well (it drops them for
//! every method outside `IsMethodExecutable`, in `CallMethod` and `FrontWrite`), so this table
//! is a subset of what the reference that ran titles drops. The tests in `regs/tests.rs` check
//! that each entry names a method of `clc797::HEADER`, that no element runs into another
//! method's first element, and that no element is one of Eden-NX2's executable methods, written
//! out there as literals.

