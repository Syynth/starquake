use super::*;

use crate::gen_classes::parse::{ClassId, parse};

/// A header with one of each kind of item, lower-case value names and a class id.
const TEXT: &str = "/*\n\
     * Copyright (c) 2020, Test Holder.\n\
     *\n\
     * Permission is hereby granted, free of charge, to any person.\n\
     */\n\
     #define TEST_CLASS (0x0000C797)\n\
     #define NVC797_SET_OBJECT 0x0000\n\
     #define NVC797_SET_OBJECT_CLASS_ID 15:0\n\
     #define NVC797_SET_OBJECT_MODE 17:16\n\
     #define NVC797_SET_OBJECT_MODE_Static 0x00000000\n\
     #define NVC797_SET_OBJECT_MODE_LARGE 0x00012345\n\
     #define NVC797_SELECT(i,j) (0x2800+(i)*128+(j)*4)\n\
     #define NVC797_SELECT_ATTRIBUTE 7:0\n\
     #define NVC797_COUNT 8\n\
     #define NVC797_ENTRY_GET 31:2\n\
     #define NVC797_HEAD_SIZE MW(38:37)\n\
     #define NVC797_HEAD_SIZE_ONE 0x00000001\n\
     #define NVC797_HEAD_VALID(i) MW((640+(i)*1):(640+(i)*1))\n";

const SOURCE: Source = Source {
    header: "clc797.h",
    only: None,
    about: "A test class.",
};

/// The module [`TEXT`] generates, checked by hand against the text above.
const EXPECTED: &str = r#"// Copyright (c) 2020, Test Holder.
//
// Permission is hereby granted, free of charge, to any person.
//
// Generated by `cargo xtask gen-classes` from
// mesa-nouveau/src/nouveau/headers/nvidia/classes/clc797.h.
// Do not edit: change the generator or the header, and regenerate.

//! A test class.
//!
//! Every define of `clc797.h` as a constant named like the header's define without the `NVC797_`
//! prefix, and all of them as one [`HEADER`] table. Byte addresses and bit ranges are the header's
//! own; method numbers (byte address / 4) come from [`Method::method`](super::Method::method).

use super::{Bits, ClassHeader, ClassId, Method, MwArray, MwField, NamedField, Value};
use crate::field::Field;

/// The class id, `TEST_CLASS`.
pub const CLASS: u32 = 0xc797;

/// `NVC797_SET_OBJECT`: method at byte address `0x0000`.
pub const SET_OBJECT: Method = Method {
    name: "SET_OBJECT",
    byte_address: 0x0000,
    strides: &[],
    fields: &[
        NamedField { name: "CLASS_ID", bits: Bits::Word(SET_OBJECT_CLASS_ID), values: &[] },
        NamedField { name: "MODE", bits: Bits::Word(SET_OBJECT_MODE), values: &[
            Value { name: "Static", value: SET_OBJECT_MODE_STATIC },
            Value { name: "LARGE", value: SET_OBJECT_MODE_LARGE },
        ] },
    ],
};
/// `NVC797_SET_OBJECT_CLASS_ID`: bits `15:0` of `SET_OBJECT`.
pub const SET_OBJECT_CLASS_ID: Field = Field::new(15, 0);
/// `NVC797_SET_OBJECT_MODE`: bits `17:16` of `SET_OBJECT`.
pub const SET_OBJECT_MODE: Field = Field::new(17, 16);
/// `NVC797_SET_OBJECT_MODE_Static`: a value of `SET_OBJECT_MODE`.
pub const SET_OBJECT_MODE_STATIC: u32 = 0x0;
/// `NVC797_SET_OBJECT_MODE_LARGE`: a value of `SET_OBJECT_MODE`.
pub const SET_OBJECT_MODE_LARGE: u32 = 0x1_2345;

/// `NVC797_SELECT`: array method, strides 128 and 4 bytes, at byte address `0x2800`.
pub const SELECT: Method = Method {
    name: "SELECT",
    byte_address: 0x2800,
    strides: &[128, 4],
    fields: &[
        NamedField { name: "ATTRIBUTE", bits: Bits::Word(SELECT_ATTRIBUTE), values: &[] },
    ],
};
/// `NVC797_SELECT_ATTRIBUTE`: bits `7:0` of `SELECT`.
pub const SELECT_ATTRIBUTE: Field = Field::new(7, 0);

/// `NVC797_ENTRY_GET`: bits `31:2`.
pub const ENTRY_GET: Field = Field::new(31, 2);
/// `NVC797_HEAD_SIZE`: bits `MW(38:37)`.
pub const HEAD_SIZE: MwField = MwField::new(38, 37);
/// `NVC797_HEAD_SIZE_ONE`: a value of `HEAD_SIZE`.
pub const HEAD_SIZE_ONE: u32 = 0x1;
/// `NVC797_HEAD_VALID`: element 0 at bits `MW(640:640)`, elements 1 bits apart.
pub const HEAD_VALID: MwArray = MwArray::new(640, 640, 1);
/// `NVC797_COUNT`.
pub const COUNT: u32 = 0x8;

/// Every method, field of no method and constant of `clc797.h`, in the header's order.
pub const HEADER: ClassHeader = ClassHeader {
    header: "clc797.h",
    class: Some(ClassId { name: "TEST_CLASS", id: CLASS }),
    methods: &[
        SET_OBJECT,
        SELECT,
    ],
    fields: &[
        NamedField { name: "ENTRY_GET", bits: Bits::Word(ENTRY_GET), values: &[] },
        NamedField { name: "HEAD_SIZE", bits: Bits::Multi(HEAD_SIZE), values: &[
            Value { name: "ONE", value: HEAD_SIZE_ONE },
        ] },
        NamedField { name: "HEAD_VALID", bits: Bits::MultiArray(HEAD_VALID), values: &[] },
    ],
    constants: &[
        Value { name: "COUNT", value: COUNT },
    ],
};
"#;

#[test]
fn a_header_with_every_kind_of_item_generates_the_expected_module() {
    let header = parse(SOURCE.header, TEXT, None).unwrap();
    assert_eq!(emit(&SOURCE, &header), EXPECTED);
}

#[test]
fn generating_twice_gives_the_same_bytes() {
    let header = parse(SOURCE.header, TEXT, None).unwrap();
    assert_eq!(emit(&SOURCE, &header), emit(&SOURCE, &header.clone()));
}

#[test]
fn a_structure_header_has_no_class_methods_or_constants_and_imports_only_what_it_uses() {
    let header = Header {
        prefix: "NVC7C0_".to_owned(),
        notice: vec!["Permission is hereby granted, free of charge.".to_owned()],
        class: None,
        methods: Vec::new(),
        fields: vec![Field {
            name: "QMDV03_00_OUTER_PUT".to_owned(),
            bits: Bits::Multi { high: 30, low: 0 },
            values: Vec::new(),
        }],
        constants: Vec::new(),
    };
    let source = Source {
        header: "clc7c0qmd.h",
        only: Some("QMDV03_00_"),
        about: "A structure.",
    };
    let text = emit(&source, &header);
    assert!(text.contains("\nuse super::{Bits, ClassHeader, MwField, NamedField};\n"));
    assert!(!text.contains("use crate::field::Field;"));
    assert!(!text.contains("pub const CLASS"));
    assert!(text.contains("    class: None,\n    methods: &[],\n"));
    assert!(text.contains("    constants: &[],\n};\n"));
    assert!(text.contains(
        "//! Every define of `clc7c0qmd.h` whose name starts with `NVC7C0_QMDV03_00_` as a \
         constant named\n//! like the header's define without the `NVC7C0_` prefix, and all of \
         them as one [`HEADER`] table.\n//! Bit ranges are the header's own.\n"
    ));
}

#[test]
fn a_header_with_only_constants_imports_value_and_lists_no_fields() {
    let header = Header {
        prefix: "NVC797_".to_owned(),
        notice: vec!["Permission is hereby granted, free of charge.".to_owned()],
        class: Some(ClassId {
            name: "ONLY".to_owned(),
            id: 0x1_0000,
        }),
        methods: Vec::new(),
        fields: Vec::new(),
        constants: vec![Value {
            name: "SIZE".to_owned(),
            value: 4,
        }],
    };
    let text = emit(&SOURCE, &header);
    assert!(text.contains("\nuse super::{ClassHeader, ClassId, Value};\n"));
    assert!(text.contains("pub const CLASS: u32 = 0x1_0000;\n"));
    assert!(text.contains("    fields: &[],\n"));
}

#[test]
fn hex_groups_by_four_digits_from_the_right_beyond_four() {
    assert_eq!(hex(0, 1), "0x0");
    assert_eq!(hex(0, 4), "0x0000");
    assert_eq!(hex(0x10c, 4), "0x010c");
    assert_eq!(hex(0xffff, 1), "0xffff");
    assert_eq!(hex(0x1_0000, 1), "0x1_0000");
    assert_eq!(hex(0x12_3456, 1), "0x12_3456");
    assert_eq!(hex(0x123_4567, 1), "0x123_4567");
    assert_eq!(hex(u32::MAX, 1), "0xffff_ffff");
    assert_eq!(hex(0x1f, 8), "0x0000_001f");
}

#[test]
fn wrapped_lines_stay_within_the_width_unless_one_word_is_longer() {
    let mut out = Out::default();
    let words = "word ".repeat(60);
    out.wrapped("//! ", &words);
    for line in out.text.lines() {
        assert!(line.len() <= WIDTH, "{line}");
        assert!(line.starts_with("//! word"));
    }
    // Every word is kept, in order.
    let kept: Vec<&str> = out
        .text
        .lines()
        .flat_map(|line| line.trim_start_matches("//! ").split(' '))
        .collect();
    assert_eq!(kept, vec!["word"; 60]);
    // A line is filled as far as the width allows: the first line's length plus the next word
    // would pass it.
    let first = out.text.lines().next().unwrap();
    assert!(first.len() + " word".len() > WIDTH);

    let mut long = Out::default();
    let word = "x".repeat(WIDTH + 10);
    long.wrapped("//! ", &format!("a {word} b"));
    assert_eq!(long.text, format!("//! a\n//! {word}\n//! b\n"));
}

