//! Writing a read [`Header`] as a Rust module of `crates/gpu/src/classes/`.
//!
//! The module holds one constant per define, named as the header names it without the class
//! prefix (`NVC797_SET_OBJECT_CLASS_ID` becomes `SET_OBJECT_CLASS_ID`), so an entry can be
//! checked against the header by eye, and a `HEADER` table that lists every method, field,
//! value and constant by name. The types are the hand-written ones of `crates/gpu/src/classes.rs`.
//!
//! The output is a pure function of the header text and the [`Source`] entry: no dates, paths
//! or versions, so regenerating from the same header gives the same bytes.

use std::collections::BTreeSet;

use super::Source;
use super::parse::{Bits, Field, Header, Method, Value};

#[cfg(test)]
mod tests;

/// The folder, relative to the reference folder, that holds the class headers. Written into
/// each generated file's header comment.
pub const HEADER_FOLDER: &str = "mesa-nouveau/src/nouveau/headers/nvidia/classes";

/// The Rust module for `header`, read from `source`.
pub fn emit(source: &Source, header: &Header) -> String {
    let prefix = header.prefix.as_str();
    let mut out = Out::default();
    for line in &header.notice {
        if line.is_empty() {
            out.line("//");
        } else {
            out.line(&format!("// {line}"));
        }
    }
    out.line("//");
    out.line("// Generated by `cargo xtask gen-classes` from");
    out.line(&format!("// {HEADER_FOLDER}/{}.", source.header));
    out.line("// Do not edit: change the generator or the header, and regenerate.");
    out.line("");
    out.wrapped("//! ", source.about);
    out.line("//!");
    out.wrapped(
        "//! ",
        &format!(
            "Every define of `{}`{} as a constant named like the header's define without the \
             `{prefix}` prefix, and all of them as one [`HEADER`] table. {}",
            source.header,
            source
                .only
                .map(|only| format!(" whose name starts with `{prefix}{only}`"))
                .unwrap_or_default(),
            if header.methods.is_empty() {
                "Bit ranges are the header's own."
            } else {
                "Byte addresses and bit ranges are the header's own; method numbers (byte \
                 address / 4) come from [`Method::method`](super::Method::method)."
            }
        ),
    );
    out.line("");
    write_imports(&mut out, header);
    out.line("");
    if let Some(class) = &header.class {
        out.line(&format!("/// The class id, `{}`.", class.name));
        out.line(&format!("pub const CLASS: u32 = {};", hex(class.id, 4)));
        out.line("");
    }
    for method in &header.methods {
        write_method(&mut out, prefix, method);
    }
    for field in &header.fields {
        write_field_const(&mut out, prefix, &field.name, field, None);
    }
    if !header.constants.is_empty() {
        for constant in &header.constants {
            out.line(&format!("/// `{prefix}{}`.", constant.name));
            out.line(&format!(
                "pub const {}: u32 = {};",
                ident(&constant.name),
                hex(constant.value, 1)
            ));
        }
        out.line("");
    }
    write_table(&mut out, source, header);
    out.text
}

/// Collected output text.
#[derive(Default)]
struct Out {
    text: String,
}

impl Out {
    fn line(&mut self, line: &str) {
        self.text.push_str(line);
        self.text.push('\n');
    }

    /// `text` as lines starting with `lead`, broken between words so that no line is longer
    /// than [`WIDTH`] unless a single word is.
    fn wrapped(&mut self, lead: &str, text: &str) {
        let mut line = String::from(lead);
        for word in text.split_whitespace() {
            if line.len() > lead.len() && line.len() + 1 + word.len() > WIDTH {
                self.line(&line);
                line = String::from(lead);
            }
            if line.len() > lead.len() {
                line.push(' ');
            }
            line.push_str(word);
        }
        self.line(&line);
    }
}

/// The longest line [`Out::wrapped`] writes, as in the workspace's hand-written code.
const WIDTH: usize = 100;

/// `value` in lower-case hex with at least `digits` digits, grouped by four from the right
/// when longer than four (the grouping clippy's literal lints accept).
fn hex(value: u32, digits: usize) -> String {
    let plain = format!("{value:0digits$x}");
    let mut grouped = String::new();
    let lead = plain.len() % 4;
    for (index, c) in plain.chars().enumerate() {
        if plain.len() > 4 && index > 0 && (index + 4 - lead) % 4 == 0 {
            grouped.push('_');
        }
        grouped.push(c);
    }
    format!("0x{grouped}")
}

/// The `use` lines: only the types the module names.
fn write_imports(out: &mut Out, header: &Header) {
    let mut used = BTreeSet::from(["ClassHeader"]);
    if header.class.is_some() {
        used.insert("ClassId");
    }
    let all_fields = header
        .methods
        .iter()
        .flat_map(|method| &method.fields)
        .chain(&header.fields);
    let mut word = false;
    for field in all_fields {
        used.insert("Bits");
        used.insert("NamedField");
        if !field.values.is_empty() {
            used.insert("Value");
        }
        match field.bits {
            Bits::Word { .. } => word = true,
            Bits::Multi { .. } => {
                used.insert("MwField");
            }
            Bits::MultiArray { .. } => {
                used.insert("MwArray");
            }
        }
    }
    if !header.methods.is_empty() {
        used.insert("Method");
    }
    if !header.constants.is_empty() {
        used.insert("Value");
    }
    let list: Vec<&str> = used.into_iter().collect();
    out.line(&format!("use super::{{{}}};", list.join(", ")));
    if word {
        out.line("use crate::field::Field;");
    }
}

/// The Rust constant name for a header name: the same, upper-cased (a few value names have
/// lower-case letters, `MONOCHROME_8x8` in `cl902d.h`; the reader refuses two names that differ
/// only in case).
fn ident(name: &str) -> String {
    name.to_ascii_uppercase()
}

fn write_method(out: &mut Out, prefix: &str, method: &Method) {
    let strides: Vec<String> = method.strides.iter().map(u32::to_string).collect();
    let shape = if method.strides.is_empty() {
        String::from("method")
    } else {
        format!("array method, strides {} bytes,", strides.join(" and "))
    };
    out.line(&format!(
        "/// `{prefix}{}`: {shape} at byte address `{}`.",
        method.name,
        hex(method.byte_address, 4)
    ));
    out.line(&format!("pub const {}: Method = Method {{", ident(&method.name)));
    out.line(&format!("    name: \"{}\",", method.name));
    out.line(&format!(
        "    byte_address: {},",
        hex(method.byte_address, 4)
    ));
    out.line(&format!("    strides: &[{}],", strides.join(", ")));
    out.line("    fields: &[");
    for field in &method.fields {
        write_named_field(out, &format!("{}_{}", method.name, field.name), field, "        ");
    }
    out.line("    ],");
    out.line("};");
    for field in &method.fields {
        let full = format!("{}_{}", method.name, field.name);
        write_field_const(out, prefix, &full, field, Some(&method.name));
    }
    out.line("");
}

/// A `NamedField` literal for `field`, whose header name (without the class prefix) is `full`.
fn write_named_field(out: &mut Out, full: &str, field: &Field, indent: &str) {
    let full = ident(full);
    let bits = match field.bits {
        Bits::Word { .. } => format!("Bits::Word({full})"),
        Bits::Multi { .. } => format!("Bits::Multi({full})"),
        Bits::MultiArray { .. } => format!("Bits::MultiArray({full})"),
    };
    if field.values.is_empty() {
        out.line(&format!(
            "{indent}NamedField {{ name: \"{}\", bits: {bits}, values: &[] }},",
            field.name
        ));
        return;
    }
    out.line(&format!(
        "{indent}NamedField {{ name: \"{}\", bits: {bits}, values: &[",
        field.name
    ));
    for value in &field.values {
        out.line(&format!(
            "{indent}    Value {{ name: \"{}\", value: {full}_{} }},",
            value.name,
            ident(&value.name)
        ));
    }
    out.line(&format!("{indent}] }},"));
}

/// The bit-range constant of a field named `full`, and one constant per value. `method` is the
/// method the field belongs to, if any.
fn write_field_const(out: &mut Out, prefix: &str, full: &str, field: &Field, method: Option<&str>) {
    let owner = method
        .map(|method| format!(" of `{method}`"))
        .unwrap_or_default();
    let name = ident(full);
    match field.bits {
        Bits::Word { high, low } => {
            out.line(&format!(
                "/// `{prefix}{full}`: bits `{high}:{low}`{owner}."
            ));
            out.line(&format!(
                "pub const {name}: Field = Field::new({high}, {low});"
            ));
        }
        Bits::Multi { high, low } => {
            out.line(&format!("/// `{prefix}{full}`: bits `MW({high}:{low})`."));
            out.line(&format!(
                "pub const {name}: MwField = MwField::new({high}, {low});"
            ));
        }
        Bits::MultiArray { high, low, stride } => {
            out.line(&format!(
                "/// `{prefix}{full}`: element 0 at bits `MW({high}:{low})`, elements {stride} \
                 bits apart."
            ));
            out.line(&format!(
                "pub const {name}: MwArray = MwArray::new({high}, {low}, {stride});"
            ));
        }
    }
    for value in &field.values {
        write_value(out, prefix, full, value);
    }
}

fn write_value(out: &mut Out, prefix: &str, full: &str, value: &Value) {
    out.line(&format!(
        "/// `{prefix}{full}_{}`: a value of `{}`.",
        value.name,
        ident(full)
    ));
    out.line(&format!(
        "pub const {}_{}: u32 = {};",
        ident(full),
        ident(&value.name),
        hex(value.value, 1)
    ));
}

fn write_table(out: &mut Out, source: &Source, header: &Header) {
    out.line(&format!(
        "/// Every method, field of no method and constant of `{}`, in the header's order.",
        source.header
    ));
    out.line("pub const HEADER: ClassHeader = ClassHeader {");
    out.line(&format!("    header: \"{}\",", source.header));
    match &header.class {
        Some(class) => out.line(&format!(
            "    class: Some(ClassId {{ name: \"{}\", id: CLASS }}),",
            class.name
        )),
        None => out.line("    class: None,"),
    }
    if header.methods.is_empty() {
        out.line("    methods: &[],");
    } else {
        out.line("    methods: &[");
        for method in &header.methods {
            out.line(&format!("        {},", ident(&method.name)));
        }
        out.line("    ],");
    }
    if header.fields.is_empty() {
        out.line("    fields: &[],");
    } else {
        out.line("    fields: &[");
        for field in &header.fields {
            write_named_field(out, &field.name, field, "        ");
        }
        out.line("    ],");
    }
    if header.constants.is_empty() {
        out.line("    constants: &[],");
    } else {
        out.line("    constants: &[");
        for constant in &header.constants {
            out.line(&format!(
                "        Value {{ name: \"{}\", value: {} }},",
                constant.name,
                ident(&constant.name)
            ));
        }
        out.line("    ],");
    }
    out.line("};");
}
