#[test]
fn each_header_becomes_the_module_named_after_it() {
    let source = |header| Source {
        header,
        only: None,
        about: "",
    };
    assert_eq!(module_file(&source("clc797.h")), "clc797.rs");
    assert_eq!(module_file(&source("clc7c0qmd.h")), "clc7c0qmd.rs");
}

#[test]
fn the_sources_are_the_classes_of_slice_g3_each_with_a_class_prefix() {
    let headers: Vec<&str> = SOURCES.iter().map(|source| source.header).collect();
    // `docs/specs/gpu-protocol.md`, row G3: C76F, C797, C7C0, C7B5, A140, 902D, QMD 3.0 and the
    // texture header; in module-name order.
    assert_eq!(
        headers,
        [
            "cl902d.h",
            "cla140.h",
            "clc76f.h",
            "clc797.h",
            "clc797tex.h",
            "clc7b5.h",
            "clc7c0.h",
            "clc7c0qmd.h"
        ]
    );
    for source in SOURCES {
        assert!(
            parse::class_prefix(source.header).is_some(),
            "{}",
            source.header
        );
    }
    let qmd: Vec<_> = SOURCES.iter().filter_map(|source| source.only).collect();
    assert_eq!(qmd, ["QMDV03_00_"]);
}

#[test]
fn the_committed_folder_holds_exactly_the_modules_of_the_sources() {
    // Needs no reference folder: a stray or missing file fails here, in CI as well.
    let committed = committed(&root()).unwrap();
    let names: Vec<&String> = committed.keys().collect();
    let expected: Vec<String> = SOURCES.iter().map(module_file).collect();
    assert_eq!(names, expected.iter().collect::<Vec<_>>());
    for (file, text) in &committed {
        assert!(
            text.contains("// Generated by `cargo xtask gen-classes` from\n"),
            "{file}"
        );
        assert!(
            text.contains("// Permission is hereby granted, free of charge"),
            "{file} lacks the MIT notice"
        );
    }
}

#[test]
fn the_gpu_crate_declares_every_generated_module_unformatted_and_lists_its_table() {
    let classes = walk::read_text(&root().join("crates/gpu/src/classes.rs")).unwrap();
    for source in SOURCES {
        let module = module_file(source);
        let module = module.trim_end_matches(".rs");
        assert!(
            classes.contains(&format!("#[rustfmt::skip]\npub mod {module};\n")),
            "{module} is not declared with #[rustfmt::skip]"
        );
        assert!(
            classes.contains(&format!("    {module}::HEADER,\n")),
            "{module}::HEADER is not in HEADERS"
        );
    }
}

/// A header reader over fixed texts, failing for any other file.
fn reader(texts: &[(&'static str, String)]) -> impl Fn(&str) -> Result<String, Unreadable> {
    let texts = texts.to_vec();
    move |file: &str| {
        texts
            .iter()
            .find(|(name, _)| *name == file)
            .map(|(_, text)| text.clone())
            .ok_or_else(|| Unreadable {
                path: file.to_owned(),
                source: io::Error::new(io::ErrorKind::NotFound, "no such file"),
            })
    }
}

/// A minimal readable header body for `file`.
fn minimal(file: &str) -> String {
    let prefix = parse::class_prefix(file).unwrap();
    format!(
        "/* Permission is hereby granted, free of charge, to any person. */\n\
         #define {prefix}NOP 0x0100\n\
         #define {prefix}NOP_V 31:0\n"
    )
}

#[test]
fn every_source_is_generated_in_order() {
    let texts: Vec<(&'static str, String)> = SOURCES
        .iter()
        .map(|source| (source.header, minimal(source.header)))
        .collect();
    let generated = generate_all(&reader(&texts)).unwrap();
    let names: Vec<&str> = generated.iter().map(|(file, _)| file.as_str()).collect();
    let expected: Vec<String> = SOURCES.iter().map(module_file).collect();
    assert_eq!(names, expected);
    // The QMD filter applies: its NOP is not under QMDV03_00_, so the module has no fields.
    let qmd = &generated[7].1;
    assert!(qmd.contains("    methods: &[],\n    fields: &[],\n"));
    assert!(generated[0].1.contains("pub const NOP: Method"));
}

#[test]
fn a_header_that_cannot_be_read_or_parsed_stops_generation_with_its_name() {
    // The first source is missing.
    let error = generate_all(&reader(&[])).unwrap_err();
    assert_eq!(error.to_string(), "cl902d.h: no such file");
    // The second source does not parse.
    let texts = vec![
        ("cl902d.h", minimal("cl902d.h")),
        (
            "cla140.h",
            "/* Permission is hereby granted, free of charge. */\n#define NVA140_A 1+2\n"
                .to_owned(),
        ),
    ];
    let error = generate_all(&reader(&texts)).unwrap_err();
    assert_eq!(
        error.to_string(),
        "cla140.h:2: 1+2 is not a number, a bit range or an array address"
    );
}

#[test]
fn written_modules_read_back_as_committed_and_other_files_are_ignored() {
    let scratch = walk::scratch_checkout("gen-classes", "write", &[]);
    let generated = files(&[("a.rs", "one\n"), ("b.rs", "two\n")]);
    write(&scratch, &generated).unwrap();
    fs::write(scratch.join(OUTPUT_FOLDER).join("notes.txt"), "not rust").unwrap();
    let read = committed(&scratch).unwrap();
    assert_eq!(read, committed_map(&[("a.rs", "one\n"), ("b.rs", "two\n")]));
    assert_eq!(compare(&generated, &read), []);
    // Writing again replaces the text.
    write(&scratch, &files(&[("a.rs", "changed\n")])).unwrap();
    assert_eq!(committed(&scratch).unwrap()["a.rs"], "changed\n");
    fs::remove_dir_all(&scratch).unwrap();
}

#[test]
fn a_missing_output_folder_is_an_error_naming_it() {
    let scratch = walk::scratch_checkout("gen-classes", "missing", &[]);
    let error = committed(&scratch).unwrap_err();
    assert_eq!(
        error.path,
        scratch.join(OUTPUT_FOLDER).display().to_string()
    );
    fs::remove_dir_all(&scratch).unwrap();
}
