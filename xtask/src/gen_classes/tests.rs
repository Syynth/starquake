use super::*;

use std::io;

/// The workspace root, from the compile-time `xtask` folder.
fn root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .unwrap()
        .to_owned()
}

fn files(list: &[(&str, &str)]) -> Vec<(String, String)> {
    list.iter()
        .map(|(file, text)| ((*file).to_owned(), (*text).to_owned()))
        .collect()
}

fn committed_map(list: &[(&str, &str)]) -> BTreeMap<String, String> {
    files(list).into_iter().collect()
}

#[test]
fn matching_files_have_no_differences() {
    let generated = files(&[("a.rs", "one"), ("b.rs", "two")]);
    assert_eq!(
        compare(
            &generated,
            &committed_map(&[("a.rs", "one"), ("b.rs", "two")])
        ),
        []
    );
}

#[test]
fn a_changed_a_missing_and_a_stray_file_are_each_reported_in_order() {
    let generated = files(&[("a.rs", "one"), ("b.rs", "two"), ("c.rs", "three")]);
    let committed = committed_map(&[("a.rs", "one"), ("c.rs", "edited"), ("z.rs", "stray")]);
    assert_eq!(
        compare(&generated, &committed),
        [
            Difference::Missing("b.rs".to_owned()),
            Difference::Changed("c.rs".to_owned()),
            Difference::Extra("z.rs".to_owned()),
        ]
    );
}

#[test]
fn a_difference_of_one_byte_is_a_change() {
    let generated = files(&[("a.rs", "text\n")]);
    assert_eq!(
        compare(&generated, &committed_map(&[("a.rs", "text")])),
        [Difference::Changed("a.rs".to_owned())]
    );
}

#[test]
fn differences_say_what_to_do_in_plain_words() {
    assert_eq!(
        Difference::Changed("clc797.rs".to_owned()).to_string(),
        "crates/gpu/src/classes/clc797.rs differs from what its header generates: run `cargo \
         xtask gen-classes` (and do not edit generated files by hand)"
    );
    assert_eq!(
        Difference::Missing("clc797.rs".to_owned()).to_string(),
        "crates/gpu/src/classes/clc797.rs is missing: run `cargo xtask gen-classes`"
    );
    assert_eq!(
        Difference::Extra("notes.rs".to_owned()).to_string(),
        "crates/gpu/src/classes/notes.rs is generated from no header in xtask's list (SOURCES in \
         xtask/src/gen_classes.rs): delete it, or add its header to the list"
    );
}

